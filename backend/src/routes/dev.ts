import { Router } from "express";
import { store } from "../store/store.js";
import { executeTool } from "../agent/tools.js";
import { sessionView } from "./view.js";

// Development-only: builds a session by calling the same BuyWise tools the agent uses, with a fixed
// script instead of Claude. Lets UI work and tests run without an Anthropic key. Mounted only when
// DEV_SEED=true and never in production.
export const dev = Router();

dev.post("/seed", async (_req, res, next) => {
  try {
    const s = store.createSession();
    s.messages.push({ role: "user", content: "I want to get into gaming. I earn $2,000 a month." });
    await executeTool(s, "update_user_profile", { goal: "get into gaming", experience: "beginner", monthly_income: 2000 });
    for (const q of ["ps5 console", "ps5 controller", "playstation plus", "ps5 game", "xbox series s", "xbox controller", "game pass", "steam deck", "steam credit"]) {
      await executeTool(s, "search_products", { query: q });
    }
    await executeTool(s, "build_solution_option", {
      name: "PS5 Slim Digital setup", approach: "Console", summary: "Sony's current console with a game, a second controller and online play.", goal_fit: 8,
      pros: ["Large exclusive library", "Great for couch co-op"], cons: ["Highest upfront cost", "Online play needs PS Plus"],
      components: [
        { product_id: "demo-ps5-slim-digital", role: "REQUIRED", kind: "HARDWARE", reason: "The console itself" },
        { product_id: "demo-game-ps5-spiderman", role: "RECOMMENDED", kind: "SOFTWARE", reason: "A first game to play" },
        { product_id: "demo-dualsense", role: "RECOMMENDED", kind: "ACCESSORY", reason: "Second player for local co-op" },
        { product_id: "demo-sub-ps-plus-essential", role: "RECOMMENDED", kind: "SUBSCRIPTION", reason: "Needed for online multiplayer" },
        { product_id: "demo-headset", role: "OPTIONAL", kind: "ACCESSORY", reason: "Voice chat" },
      ],
      bundle: { bundle_product_id: "demo-ps5-bundle-cod", replaces_product_ids: ["demo-ps5-slim-digital", "demo-game-ps5-spiderman"] },
    });
    await executeTool(s, "build_solution_option", {
      name: "Xbox Series S + Game Pass", approach: "Console", summary: "Lowest-cost current console; Game Pass covers the games library.", goal_fit: 8,
      pros: ["Lowest upfront cost", "Hundreds of games via Game Pass"], cons: ["512GB storage fills quickly", "No disc drive"],
      components: [
        { product_id: "demo-xbox-series-s", role: "REQUIRED", kind: "HARDWARE", reason: "The console itself" },
        { product_id: "demo-xbox-controller", role: "RECOMMENDED", kind: "ACCESSORY", reason: "Second player" },
        { product_id: "demo-sub-game-pass-ultimate", role: "RECOMMENDED", kind: "SUBSCRIPTION", reason: "Games library and online play" },
      ],
    });
    await executeTool(s, "build_solution_option", {
      name: "Steam Deck OLED", approach: "Handheld", summary: "Portable PC gaming with the whole Steam library.", goal_fit: 7,
      pros: ["Portable", "No subscription needed"], cons: ["Smaller screen", "Games bought individually"],
      components: [
        { product_id: "demo-steam-deck-oled", role: "REQUIRED", kind: "HARDWARE", reason: "The handheld" },
        { product_id: "demo-game-steam-credit", role: "RECOMMENDED", kind: "SOFTWARE", reason: "Credit for first games" },
      ],
    });
    await executeTool(s, "rank_options", {});
    const top = s.options[0];
    s.messages.push({
      role: "assistant",
      content: `**${top.name}** ranks first on first-year cost and budget fit. (Seeded dev session - generated by the scripted tool sequence, not by Claude.)`,
    });
    store.saveSession(s);
    res.status(201).json(sessionView(s, []));
  } catch (err) {
    next(err);
  }
});
